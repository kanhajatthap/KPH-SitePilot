/**
 * Our own transactional mail transport (Resend HTTP API).
 *
 * Supabase's built-in mailer is a *testing* mailer: it delivers to project
 * members and throttles to a couple of messages per hour. The cure for that is
 * custom SMTP, which can only be set inside a dashboard owned by the project's
 * account — so when the deployment and the project belong to different people,
 * authentication email is blocked on something the deployment cannot touch.
 *
 * This module takes the mailer off that critical path. When `RESEND_API_KEY`
 * and `SITEPILOT_MAIL_FROM` are set the app mails its own confirmation and
 * recovery links, generated by `email-links.ts`. When they are not set, every
 * caller falls back to the previous Supabase path — so the change is additive
 * and nothing starts behaving differently just because a variable is missing.
 *
 * Three rules hold here:
 *
 *  - the API key never leaves this file and never appears in a result value;
 *  - the transport never throws. "We could not send" is a value, because it has
 *    to reach the user as copy, not as a 500;
 *  - time is bounded, so a stalled provider cannot hold a server action open.
 */

export type AuthMailKind = 'confirmation' | 'recovery';

export interface MailerConfig {
  apiKey: string;
  from: string;
  replyTo: string | null;
}

export type MailFailureReason = 'not-configured' | 'invalid-input' | 'rejected' | 'unreachable';

export type MailResult =
  | { ok: true; id: string | null }
  | { ok: false; reason: MailFailureReason; status: number | null };

const RESEND_ENDPOINT = 'https://api.resend.com/emails';
const KEY_PREFIX = 're_';

/** Bound on the whole request: a mailer must never hang a form submission. */
export const MAIL_TIMEOUT_MS = 10_000;

const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
/** `no-reply@example.com` or the `Name <no-reply@example.com>` form. */
const SENDER = /^(?:[^<>]{1,80}<\s*)?[^\s@<>]+@[^\s@<>]+\.[^\s@<>]{2,}\s*>?$/;

type Env = Record<string, string | undefined>;

/**
 * Reads the mailer configuration, or `null` when it is absent/incomplete.
 *
 * Both halves are required on purpose: a key with no sender address is a
 * misconfiguration that would fail on every send, and returning `null` keeps
 * callers on the working fallback instead of discovering that per-request.
 */
export function mailerConfig(env: Env = process.env): MailerConfig | null {
  const apiKey = (env.RESEND_API_KEY ?? '').trim();
  const from = (env.SITEPILOT_MAIL_FROM ?? '').trim();
  if (!apiKey.startsWith(KEY_PREFIX) || apiKey.length < 12) return null;
  if (!SENDER.test(from)) return null;

  const replyTo = (env.SITEPILOT_MAIL_REPLY_TO ?? '').trim();
  return { apiKey, from, replyTo: EMAIL.test(replyTo) ? replyTo : null };
}

/**
 * Secret-free summary for `/api/auth/status`.
 *
 * The sender address is not a secret — it is printed in every mail we send —
 * and knowing it is the difference between "the app has its own mailer" and
 * "nobody can tell".
 */
export function mailerStatus(env: Env = process.env): {
  configured: boolean;
  provider: 'resend';
  from: string | null;
} {
  const config = mailerConfig(env);
  return { configured: Boolean(config), provider: 'resend', from: config?.from ?? null };
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export interface AuthMail {
  subject: string;
  html: string;
  text: string;
}

const COPY: Record<AuthMailKind, { subject: string; lead: string; action: string; ignore: string }> = {
  confirmation: {
    subject: 'Confirm your KPH SitePilot email address',
    lead: 'One click and your KPH SitePilot account is active.',
    action: 'Confirm email address',
    ignore: 'If you did not create an account, ignore this message — nothing happens without this click.',
  },
  recovery: {
    subject: 'Reset your KPH SitePilot password',
    lead: 'Use the link below to choose a new password.',
    action: 'Choose a new password',
    ignore: 'If you did not ask for a reset, ignore this message — your password stays as it is.',
  },
};

/**
 * Builds both parts of the message.
 *
 * The URL is HTML-escaped in the markup but left alone in the plain-text part
 * and in the anchor's target, because `&` is a query separator here — escaping
 * it into the href would break the token.
 */
export function buildAuthMail(kind: AuthMailKind, url: string): AuthMail {
  const copy = COPY[kind];
  const safeUrl = escapeHtml(url);
  const html = [
    '<div style="font-family:system-ui,-apple-system,Segoe UI,sans-serif;max-width:520px;line-height:1.5">',
    `<p>${copy.lead}</p>`,
    `<p><a href="${safeUrl}" style="display:inline-block;padding:12px 20px;border-radius:8px;background:#111;color:#fff;text-decoration:none">${copy.action}</a></p>`,
    `<p style="color:#555;font-size:14px">If the button does not work, paste this into your browser:<br><span style="word-break:break-all">${safeUrl}</span></p>`,
    `<p style="color:#888;font-size:13px">${copy.ignore}</p>`,
    '</div>',
  ].join('');

  const text = [copy.lead, '', `${copy.action}: ${url}`, '', copy.ignore].join('\n');
  return { subject: copy.subject, html, text };
}

export interface SendAuthMailInput {
  to: string;
  kind: AuthMailKind;
  url: string;
  env?: Env;
  /** Injected in tests; defaults to the global fetch. */
  fetchImpl?: typeof fetch;
  timeoutMs?: number;
}

/**
 * Sends one authentication mail. Never throws.
 *
 * `rejected` (the provider answered, and said no — unverified domain, bad
 * sender) is separated from `unreachable` (nothing answered) because only the
 * second one means "your network/project is down"; the first is a config fix.
 */
export async function sendAuthMail(input: SendAuthMailInput): Promise<MailResult> {
  const to = input.to.trim().toLowerCase();
  if (!EMAIL.test(to)) return { ok: false, reason: 'invalid-input', status: null };

  const config = mailerConfig(input.env ?? process.env);
  if (!config) return { ok: false, reason: 'not-configured', status: null };

  const mail = buildAuthMail(input.kind, input.url);
  const body: Record<string, unknown> = {
    from: config.from,
    to: [to],
    subject: mail.subject,
    html: mail.html,
    text: mail.text,
  };
  if (config.replyTo) body.reply_to = config.replyTo;

  const doFetch = input.fetchImpl ?? fetch;
  const timeoutMs = input.timeoutMs ?? MAIL_TIMEOUT_MS;

  try {
    const response = await doFetch(RESEND_ENDPOINT, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${config.apiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(timeoutMs),
    });

    if (!response.ok) {
      return { ok: false, reason: 'rejected', status: response.status };
    }

    // The id is useful in a support conversation; the response shape is not
    // guaranteed, so a missing id is not a failure.
    const payload = (await response.json().catch(() => null)) as { id?: unknown } | null;
    const id = typeof payload?.id === 'string' ? payload.id : null;
    return { ok: true, id };
  } catch {
    return { ok: false, reason: 'unreachable', status: null };
  }
}
